#!/usr/bin/env node
'use strict';
// node db/tools/dictionary.js [--check] — generate docs/db/DATA_DICTIONARY.md from a fresh build:
// every table and column with type, nullability, default, FK target and ON DELETE, CHECKs, and the
// purpose comments written next to them in db/schema. --check fails if the committed file is stale
// (run by npm test), so the dictionary can't drift from the schema.

const fs = require('fs');
const path = require('path');
const { ROOT, buildDatabase, listModules, SCHEMA_DIR } = require('./lib/schema');
const { parseCreateTable, checkExpressions, stripComments } = require('./lib/sql');

const OUT = path.join(ROOT, 'docs', 'db', 'DATA_DICTIONARY.md');

// Secret-bearing columns (CLAUDE.md convention 15; req 75, 98, 102). Support bundles and exports
// must drop or redact these. *_enc = DPAPI ciphertext; *_hash of a password/PIN/token = verifier.
const SECRET = /(_enc$)|(^(password|pin|token)_hash$)/;

/** Comments from the module source: {table: {comment, columns: {col: comment}}, moduleOf: {table: module}}. */
function sourceComments() {
  const out = {};
  for (const m of listModules(SCHEMA_DIR)) {
    const lines = m.sql.split(/\r?\n/);
    for (let i = 0; i < lines.length; i++) {
      const t = /^CREATE TABLE (\w+)/.exec(lines[i]);
      if (!t) continue;
      const pre = [];
      for (let j = i - 1; j >= 0 && /^--/.test(lines[j]) && !/^-- -{5,}/.test(lines[j]); j--) pre.unshift(lines[j].replace(/^--\s?/, ''));
      const cols = {};
      let last = null;
      for (let k = i + 1; k < lines.length && !/^\)/.test(lines[k]); k++) {
        const c = /^\s{4}(\w+)\s+(INTEGER|TEXT|REAL|BLOB|ANY)\b/.exec(lines[k]);
        const cm = /--\s*(.+)$/.exec(lines[k]);
        if (c) { last = c[1]; if (cm) cols[last] = cm[1].trim(); }
        else if (last && cm && /^\s+--/.test(lines[k]) === false) cols[last] = [cols[last], cm[1].trim()].filter(Boolean).join(' ');
        else if (last && cm && /^\s{20,}--/.test(lines[k])) cols[last] = [cols[last], cm[1].trim()].filter(Boolean).join(' ');
      }
      out[t[1]] = { module: m.name, comment: pre.join(' ').trim(), columns: cols };
    }
  }
  return out;
}

// Purpose of the convention columns repeated on many tables (CLAUDE.md conventions 2, 5, 10).
const STANDARD = {
  id: 'Surrogate key',
  created_at: 'Row created (UTC ms)',
  updated_at: 'Last change (UTC ms); set by every update (P8)',
  updated_by_user_account_id: 'Who made the last change; NULL = service/system (P8)',
  row_version: 'Optimistic concurrency: UPDATE ... WHERE id=? AND row_version=? then +1 (P8, req 86)',
};

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

function render() {
  const db = buildDatabase(':memory:', { seed: false });
  const notes = sourceComments();
  const tables = db.prepare(`SELECT name, sql FROM sqlite_schema WHERE type = 'table' AND name NOT LIKE 'sqlite_%'`).all();
  const order = Object.keys(notes);
  tables.sort((a, b) => order.indexOf(a.name) - order.indexOf(b.name));

  const secrets = [];
  const out = [];
  out.push('# Data dictionary — workstation database');
  out.push('');
  out.push('Generated by `node db/tools/dictionary.js` from a fresh build of `db/schema` and the comments in the modules. **Do not edit by hand.** `npm test` fails if this file is stale. Requirement IDs are in the purpose text; the full mapping is in TRACEABILITY.md.');
  out.push('');
  out.push(`Schema version (PRAGMA user_version): **${db.pragma('user_version', { simple: true })}** · ${tables.length} tables.`);
  out.push('');

  let module = null;
  for (const t of tables) {
    const n = notes[t.name] || { columns: {} };
    if (n.module !== module) { module = n.module; out.push(`## ${module}`, ''); }
    const info = db.prepare('SELECT strict, wr FROM pragma_table_list WHERE name = ?').get(t.name);
    const fks = Object.fromEntries(db.pragma(`foreign_key_list("${t.name}")`).map((f) => [f.from, f]));
    const parsed = parseCreateTable(t.sql);
    const flags = [info.strict ? 'STRICT' : 'not STRICT', info.wr ? 'WITHOUT ROWID' : null, /AUTOINCREMENT/i.test(t.sql) ? 'AUTOINCREMENT' : null].filter(Boolean).join(', ');
    out.push(`### ${t.name}`, '');
    if (n.comment) out.push(cell(n.comment), '');
    out.push(`*${flags}*`, '');
    out.push('| Column | Type | Null | Default | References (ON DELETE) | Checks | Purpose |');
    out.push('|---|---|---|---|---|---|---|');
    for (const c of db.pragma(`table_xinfo("${t.name}")`)) {
      const fk = fks[c.name];
      const def = (parsed.columns.find((p) => p.name === c.name) || {}).def || '';
      const checks = checkExpressions(stripComments(def)).map((e) => `\`${cell(e)}\``).join('<br>');
      const isSecret = SECRET.test(c.name);
      if (isSecret) secrets.push(`${t.name}.${c.name}`);
      out.push(`| ${c.pk ? '**' + c.name + '** (PK)' : c.name}${isSecret ? ' 🔒' : ''} | ${c.type} | ${c.notnull || c.pk ? 'no' : 'yes'} | ${c.dflt_value == null ? '' : '`' + cell(c.dflt_value) + '`'} | ${fk ? `${fk.table}(${fk.to || 'id'}) ${fk.on_delete}` : ''} | ${checks} | ${cell(n.columns[c.name] || STANDARD[c.name])} |`);
    }
    const tableChecks = parsed.constraints.filter((k) => /^CHECK\b/i.test(k)).map((k) => `\`${cell(k.replace(/^CHECK\s*/i, ''))}\``);
    const uniques = parsed.constraints.filter((k) => /^UNIQUE\b/i.test(k)).map((k) => `\`${cell(k)}\``);
    if (tableChecks.length) out.push('', `Table checks: ${tableChecks.join(' · ')}`);
    if (uniques.length) out.push('', `Unique: ${uniques.join(' · ')}`);
    const ix = db.prepare(`SELECT name FROM sqlite_schema WHERE type = 'index' AND tbl_name = ? AND sql IS NOT NULL ORDER BY name`).all(t.name).map((r) => `\`${r.name}\``);
    const tr = db.prepare(`SELECT name FROM sqlite_schema WHERE type = 'trigger' AND tbl_name = ? ORDER BY name`).all(t.name).map((r) => `\`${r.name}\``);
    if (ix.length) out.push('', `Indexes: ${ix.join(', ')}`);
    if (tr.length) out.push('', `Triggers: ${tr.join(', ')}`);
    out.push('');
  }

  out.push('## Secret-bearing columns (redact in support bundles and exports)', '');
  out.push('CLAUDE.md convention 15; req 75, 98, 102. Support bundles, exports and settings portability must drop or redact these columns. `*_enc` holds DPAPI ciphertext; password, PIN and token hashes are verifiers and must never leave the machine. Columns are marked 🔒 above.', '');
  for (const s of secrets) out.push(`- \`${s}\``);
  out.push('');
  db.close();
  return out.join('\n');
}

if (require.main === module) {
  const text = render();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('DATA_DICTIONARY.md is stale: run node db/tools/dictionary.js'); process.exit(1); }
    console.log('DATA_DICTIONARY.md is up to date');
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
  }
}

module.exports = { render, OUT, SECRET };
